export interface LandingExportImage {
  path: string
  imageBase64: string
}

function slugify(value: string) {
  return (
    value
      .trim()
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '') || 'landing-page'
  )
}

function base64ToBytes(imageBase64: string): Uint8Array {
  const cleaned = imageBase64.replace(/^data:[^;]+;base64,/i, '')
  const binary = atob(cleaned)
  const bytes = new Uint8Array(binary.length)
  for (let i = 0; i < binary.length; i += 1) {
    bytes[i] = binary.charCodeAt(i)
  }
  return bytes
}

function zipPathForImage(publicPath: string): string {
  return publicPath.replace(/^\//, '')
}

function ensureClientDirective(code: string): string {
  if (code.includes("'use client'") || code.includes('"use client"')) {
    return code
  }
  return `'use client'\n\n${code}`
}

function imageZipEntries(
  images: LandingExportImage[],
  prefix: string,
): Array<{ path: string; data: Uint8Array }> {
  return images.map((image) => ({
    path: `${prefix}${zipPathForImage(image.path)}`,
    data: base64ToBytes(image.imageBase64),
  }))
}

