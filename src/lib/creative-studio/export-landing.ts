function fallbackHtml(reactCode: string): string {
  const escaped = reactCode
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')

  return `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>Landing page</title>
    <style>
      body { margin: 0; font-family: ui-sans-serif, system-ui, sans-serif; background: #0a0a0a; color: #fafafa; }
      pre { margin: 0; padding: 24px; overflow: auto; font-size: 12px; line-height: 1.5; }
    </style>
  </head>
  <body>
    <pre>${escaped}</pre>
  </body>
</html>
`
}

export async function downloadLandingVariant(input: {
  variant: GeneratedLandingVariant
  format: LandingDownloadFormat
  slug?: string
  images?: LandingExportImage[]
}): Promise<void> {
  const slug = slugify(
    input.slug || input.variant.title || input.variant.label || 'landing-page',
  )
  const images = input.images ?? []
  const reactCode = input.variant.reactCode?.trim() ?? ''
  const htmlCode = input.variant.htmlCode?.trim() ?? ''

  if (input.format === 'html') {
    const documentHtml = htmlCode || fallbackHtml(reactCode)
    if (images.length === 0) {
      downloadTextFile(documentHtml, `${slug}.html`, 'text/html')
      return
    }

    const blob = buildZip([
      { path: 'index.html', data: documentHtml },
      ...imageZipEntries(images, ''),
    ])
    triggerBlobDownload(blob, `${slug}-html.zip`)
    return
  }

  if (!reactCode) {
    throw new Error('This variant has no React code to export')
  }

  const files =
    input.format === 'nextjs'
      ? nextFiles({ slug, reactCode })
      : viteFiles({ slug, reactCode })
  const blob = buildZip([
    ...files,
    ...imageZipEntries(images, 'public/'),
  ])
  triggerBlobDownload(blob, `${slug}-${input.format}.zip`)
}

export function injectPreviewAssets(
  html: string,
  images: Array<{ path: string; dataUrl: string }>,
): string {
  return images.reduce(
    (documentHtml, image) => documentHtml.split(image.path).join(image.dataUrl),
    html,
  )
}
