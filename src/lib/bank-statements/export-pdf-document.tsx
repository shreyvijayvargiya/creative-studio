import { Document, Page, StyleSheet, Text, View } from '@react-pdf/renderer'
import type { ReactElement } from 'react'

import type { BankStatementMeta, BankTransactionDraft } from '#/types/bank-statement'

const styles = StyleSheet.create({
  page: {
    padding: 36,
    fontFamily: 'Helvetica',
    fontSize: 9,
  },
  title: {
    fontSize: 16,
    fontFamily: 'Helvetica-Bold',
    marginBottom: 4,
  },
  subtitle: {
    fontSize: 10,
    color: '#525252',
    marginBottom: 12,
  },
  metaRow: {
    flexDirection: 'row',
    marginBottom: 3,
  },
  metaLabel: {
    width: 110,
    color: '#737373',
  },
  metaValue: {
    flex: 1,
  },
  rule: {
    borderBottomWidth: 1,
    borderBottomColor: '#d4d4d4',
    marginVertical: 12,
  },
  header: {
    flexDirection: 'row',
    backgroundColor: '#f5f5f5',
    borderBottomWidth: 1,
    borderBottomColor: '#d4d4d4',
    paddingVertical: 5,
    paddingHorizontal: 3,
    fontFamily: 'Helvetica-Bold',
  },
  row: {
    flexDirection: 'row',
    borderBottomWidth: 1,
    borderBottomColor: '#e5e5e5',
    paddingVertical: 5,
    paddingHorizontal: 3,
  },
  rowAlt: {
    backgroundColor: '#fafafa',
  },
  colDate: { width: '12%' },
  colDesc: { width: '38%' },
  colAmount: { width: '12%', textAlign: 'right' },
  colDir: { width: '10%' },
  colBal: { width: '12%', textAlign: 'right' },
  colCat: { width: '16%' },
  footer: {
    marginTop: 14,
    fontSize: 8,
    color: '#737373',
  },
})

function formatMoney(value: number | null | undefined): string {
  if (value === null || value === undefined || Number.isNaN(value)) return '—'
  return value.toLocaleString('en-AU', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })
}

export function createBankStatementPdfDocument(input: {
  meta: Partial<BankStatementMeta> & { fileName?: string }
  transactions: BankTransactionDraft[]
}): ReactElement {
  const { meta, transactions } = input

  return (
    <Document>
      <Page size="A4" style={styles.page}>
        <Text style={styles.title}>Bank statement transactions</Text>
        <Text style={styles.subtitle}>{meta.fileName ?? 'Extracted statement'}</Text>

        <View style={styles.metaRow}>
          <Text style={styles.metaLabel}>Bank</Text>
          <Text style={styles.metaValue}>{meta.bankName ?? '—'}</Text>
        </View>
        <View style={styles.metaRow}>
          <Text style={styles.metaLabel}>Account</Text>
          <Text style={styles.metaValue}>
            {[meta.accountName, meta.accountNumber].filter(Boolean).join(' · ') || '—'}
          </Text>
        </View>
        <View style={styles.metaRow}>
          <Text style={styles.metaLabel}>Period</Text>
          <Text style={styles.metaValue}>
            {[meta.periodStart, meta.periodEnd].filter(Boolean).join(' → ') || '—'}
          </Text>
        </View>
        <View style={styles.metaRow}>
          <Text style={styles.metaLabel}>Currency</Text>
          <Text style={styles.metaValue}>{meta.currency ?? 'AUD'}</Text>
        </View>

        <View style={styles.rule} />

        <View style={styles.header}>
          <Text style={styles.colDate}>Date</Text>
          <Text style={styles.colDesc}>Description</Text>
          <Text style={styles.colAmount}>Amount</Text>
          <Text style={styles.colDir}>Type</Text>
          <Text style={styles.colBal}>Balance</Text>
          <Text style={styles.colCat}>Category</Text>
        </View>

        {transactions.map((txn, index) => (
          <View
            key={txn.id}
            style={index % 2 === 0 ? styles.row : [styles.row, styles.rowAlt]}
            wrap={false}
          >
            <Text style={styles.colDate}>{txn.date}</Text>
            <Text style={styles.colDesc}>{txn.description}</Text>
            <Text style={styles.colAmount}>{formatMoney(txn.amount)}</Text>
            <Text style={styles.colDir}>{txn.direction}</Text>
            <Text style={styles.colBal}>{formatMoney(txn.balance)}</Text>
            <Text style={styles.colCat}>{txn.category ?? '—'}</Text>
          </View>
        ))}

        <Text style={styles.footer}>
          {transactions.length} transaction(s) · Generated by Finance CRM
        </Text>
      </Page>
    </Document>
  )
}
